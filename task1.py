"""
## Задача 1 — максимальная цифра числа

Программа запрашивает у пользователя натуральное число, меньшее `1_000_000_000`.  
Если пользователь ввёл число вне диапазона, программа выводит строку `Input error` и останавливается.  
Иначе выводится **самая большая цифра** введённого числа. 

**Пример:**

- Дано: `123_000_365`
- Результат: `6`
"""


number = int(input("Input number less than 1_000_000_000: "))

if 0 <= number <= 1_000_000_000:
    digit = 0
    while number > 0:
        number, rest = number // 10, number % 10
        digit = max(digit, rest)

    print("maximum digit is ", digit)
else:
    print("Input error")
